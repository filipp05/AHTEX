test('editor has no user management; login has readable errors and logout revokes access',async({page})=>{
 await page.goto('/admin/')
 await page.getByLabel('Логин',{exact:true}).fill('editor');await page.getByLabel('Пароль',{exact:true}).fill('wrong')
 await page.getByRole('button',{name:'Войти',exact:true}).click();await expect(page.locator('.admin-error')).toContainText('Неверный логин или пароль')
 await page.getByLabel('Пароль',{exact:true}).fill('Test-only-password-123');await page.getByRole('button',{name:'Войти',exact:true}).click()
 await expect(page.getByRole('button',{name:'+ Добавить',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Доступы',exact:true})).toHaveCount(0)
 expect((await page.request.get('/api/admin/users')).status()).toBe(403)
 await page.getByRole('button',{name:'Выйти',exact:true}).click()
 await expect(page.getByRole('button',{name:'Войти',exact:true})).toBeVisible()
 expect((await page.request.get('/api/admin/items')).status()).toBe(401)
})


test('stale edit keeps local text and unsaved navigation asks for confirmation',async({page})=>{
 await page.goto('/admin/')
 await page.getByLabel('Логин',{exact:true}).fill('owner');await page.getByLabel('Пароль',{exact:true}).fill('Test-only-password-123')
 await page.getByRole('button',{name:'Войти',exact:true}).click()
 await page.getByRole('button',{name:'+ Добавить',exact:true}).click()
 await page.getByLabel('Название *',{exact:true}).fill('Конфликт версий')
 await page.getByLabel('Краткое описание *').fill('Исходный текст')
 await page.getByRole('button',{name:'Сохранить черновик',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Черновик сохранён')
 const session=await (await page.request.get('/api/admin/me')).json()
 const records=await (await page.request.get('/api/admin/items')).json()
 const item=records.items.find((i:{draft:{title:string}})=>i.draft.title==='Конфликт версий')
 await page.getByLabel('Краткое описание *').fill('Мой несохранённый текст')
 const update=await page.request.post('/api/admin/items',{headers:{origin:'http://127.0.0.1:3100','x-csrf-token':session.csrf},data:{id:item.id,version:item.version,action:'draft',content:{...item.draft,description:'Другой сотрудник'}}})
 expect(update.status()).toBe(200)
 await page.getByRole('button',{name:'Сохранить черновик',exact:true}).click()
 await expect(page.locator('.admin-error')).toContainText('другой сотрудник')
 await expect(page.getByLabel('Краткое описание *')).toHaveValue('Мой несохранённый текст')
 await expect(page.getByRole('button',{name:'Опубликовать',exact:true})).toBeDisabled()
 page.once('dialog',d=>d.dismiss())
 await page.getByRole('button',{name:'Закрыть',exact:true}).click()
 await expect(page.getByLabel('Краткое описание *')).toHaveValue('Мой несохранённый текст')
 page.once('dialog',d=>d.accept())
 await page.getByRole('button',{name:'Закрыть',exact:true}).click()
 await expect(page.getByLabel('Краткое описание *')).toHaveCount(0)
})
